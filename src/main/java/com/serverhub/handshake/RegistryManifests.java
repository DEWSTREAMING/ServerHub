import com.google.gson.Gson;
import com.google.gson.JsonParseException;
import com.mojang.logging.LogUtils;
import io.netty.buffer.Unpooled;
import it.unimi.dsi.fastutil.ints.IntArrayList;
import it.unimi.dsi.fastutil.ints.IntList;
import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;
import javax.annotation.Nullable;
import net.minecraft.core.Registry;
import net.minecraft.core.RegistryAccess;
import net.minecraft.core.RegistrySynchronization;
import net.minecraft.network.FriendlyByteBuf;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.TagNetworkSerialization;
import net.neoforged.fml.loading.FMLPaths;
import org.slf4j.Logger;

/**
 * Per-modpack registry manifests generated by {@code tools/scan_client_registries.py}.
 *
 * <p>A manifest lists the synced data-driven registry entries and tag names that a modpack's
 * client-side mods expect a server to provide. On the Hub, a joining client whose network
 * namespaces match a manifest receives empty-data stub entries (the client loads the real data
 * from its own mod resources) plus empty placeholders for every tag the pack defines, so mod code
 * that resolves those keys during login does not crash.
 */
public final class RegistryManifests {
    private static final Logger LOGGER = LogUtils.getLogger();
    private static final Gson GSON = new Gson();
    private static final Set<String> IMPLICIT_NAMESPACES =
            Set.of("minecraft", "neoforge", "c", "common", "forge", "fabric");
    private static final double MIN_MATCH_RATIO = 0.85D;
    private static final int MIN_MATCH_COUNT = 5;

    private static volatile List<Manifest> manifests = List.of();
    private static volatile boolean loaded;

    private RegistryManifests() {}

    public static final class Manifest {
        public String packId = "";
        public String minecraftVersion = "";
        public List<String> modIds = new ArrayList<>();
        public Map<String, List<String>> registries = new LinkedHashMap<>();
        public Map<String, List<String>> tags = new LinkedHashMap<>();

        private transient Set<String> modIdSet;

        Set<String> modIdSet() {
            Set<String> set = this.modIdSet;
            if (set == null) {
                set = new HashSet<>(IMPLICIT_NAMESPACES);
                if (this.modIds != null) {
                    set.addAll(this.modIds);
                }
                this.modIdSet = set;
            }
            return set;
        }

        void normalize() {
            if (this.packId == null) {
                this.packId = "";
            }
            if (this.modIds == null) {
                this.modIds = new ArrayList<>();
            }
            if (this.registries == null) {
                this.registries = new LinkedHashMap<>();
            }
            if (this.tags == null) {
                this.tags = new LinkedHashMap<>();
            }
        }

        public int entryCount() {
            return this.registries.values().stream().mapToInt(List::size).sum();
        }

        public int tagCount() {
            return this.tags.values().stream().mapToInt(List::size).sum();
        }
    }

    public static Path directory() {
        return FMLPaths.CONFIGDIR.get().resolve("serverhub").resolve("registry-manifests");
    }

    public static synchronized void reload() {
        Path dir = directory();
        List<Manifest> result = new ArrayList<>();
        try {
            Files.createDirectories(dir);
            try (DirectoryStream<Path> stream = Files.newDirectoryStream(dir, "*.json")) {
                for (Path file : stream) {
                    Manifest manifest = read(file);
                    if (manifest != null) {
                        result.add(manifest);
                    }
                }
            }
        } catch (IOException e) {
            LOGGER.warn("Failed to read registry manifests from {}", dir, e);
        }
        manifests = List.copyOf(result);
        loaded = true;
        for (Manifest manifest : result) {
            LOGGER.info(
                    "Loaded registry manifest '{}' (MC {}, {} mods, {} entries, {} tags)",
                    manifest.packId,
                    manifest.minecraftVersion,
                    manifest.modIds.size(),
                    manifest.entryCount(),
                    manifest.tagCount());
        }
    }

    @Nullable
    private static Manifest read(Path file) {
        try (Reader reader = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
            Manifest manifest = GSON.fromJson(reader, Manifest.class);
            if (manifest == null) {
                return null;
            }
            manifest.normalize();
            if (manifest.packId.isBlank()) {
                String name = file.getFileName().toString();
                manifest.packId = name.substring(0, name.length() - ".json".length());
            }
            return manifest;
        } catch (IOException | JsonParseException e) {
            LOGGER.warn("Failed to parse registry manifest {}", file, e);
            return null;
        }
    }

    public static synchronized void setForTesting(List<Manifest> values) {
        List<Manifest> copy = new ArrayList<>();
        for (Manifest manifest : values) {
            manifest.normalize();
            copy.add(manifest);
        }
        manifests = List.copyOf(copy);
        loaded = true;
    }

    public static List<Manifest> all() {
        if (!loaded) {
            reload();
        }
        return manifests;
    }

    /** Returns the manifest whose mod list best covers the client's network namespaces. */
    @Nullable
    public static Manifest match(Set<String> clientNamespaces) {
        if (clientNamespaces == null || clientNamespaces.isEmpty()) {
            return null;
        }
        Manifest best = null;
        int bestCount = 0;
        for (Manifest manifest : all()) {
            Set<String> known = manifest.modIdSet();
            int matched = 0;
            int considered = 0;
            for (String ns : clientNamespaces) {
                if (IMPLICIT_NAMESPACES.contains(ns)) {
                    continue;
                }
                considered++;
                if (known.contains(ns)) {
                    matched++;
                }
            }
            if (considered == 0 || matched < MIN_MATCH_COUNT) {
                continue;
            }
            double ratio = (double) matched / considered;
            if (ratio >= MIN_MATCH_RATIO && matched > bestCount) {
                best = manifest;
                bestCount = matched;
            }
        }
        return best;
    }

    @Nullable
    public static Manifest forPlayer(@Nullable UUID playerId) {
        if (playerId == null) {
            return null;
        }
        return match(ClientModTracker.getClientMods(playerId));
    }

    /**
     * Merges stub entries from {@code manifest} into {@code originalEntries} for a registry packet
     * already being sent by the Hub, returning {@code originalEntries} unchanged if nothing was
     * added.
     */
    public static List<RegistrySynchronization.PackedRegistryEntry> mergeRegistryEntries(
            ResourceKey<? extends Registry<?>> registryKey,
            List<RegistrySynchronization.PackedRegistryEntry> originalEntries,
            Manifest manifest) {
        List<String> ids = manifest.registries.get(registryKey.location().toString());
        if (ids == null || ids.isEmpty()) {
            return originalEntries;
        }
        Set<ResourceLocation> seen = new HashSet<>(originalEntries.size() * 2);
        for (RegistrySynchronization.PackedRegistryEntry entry : originalEntries) {
            seen.add(entry.id());
        }
        List<RegistrySynchronization.PackedRegistryEntry> merged = null;
        for (String id : ids) {
            ResourceLocation location = ResourceLocation.tryParse(id);
            if (location == null || !seen.add(location)) {
                continue;
            }
            if (merged == null) {
                merged = new ArrayList<>(originalEntries.size() + ids.size());
                merged.addAll(originalEntries);
            }
            merged.add(new RegistrySynchronization.PackedRegistryEntry(location, Optional.empty()));
        }
        return merged != null ? merged : originalEntries;
    }

    /**
     * Builds empty-data stub entries for each manifest registry, skipping entries the Hub already
     * syncs itself.
     */
    public static Map<ResourceKey<Registry<Object>>, List<RegistrySynchronization.PackedRegistryEntry>>
            buildStubEntries(Manifest manifest, @Nullable RegistryAccess hubRegistries) {
        Map<ResourceKey<Registry<Object>>, List<RegistrySynchronization.PackedRegistryEntry>> result =
                new LinkedHashMap<>();
        manifest.registries.forEach((registryId, ids) -> {
            ResourceLocation registryLocation = ResourceLocation.tryParse(registryId);
            if (registryLocation == null || ids == null || ids.isEmpty()) {
                return;
            }
            ResourceKey<Registry<Object>> key = ResourceKey.createRegistryKey(registryLocation);
            Optional<? extends Registry<Object>> hubRegistry =
                    hubRegistries == null ? Optional.empty() : hubRegistries.registry(key);
            List<RegistrySynchronization.PackedRegistryEntry> entries = new ArrayList<>();
            Set<ResourceLocation> seen = new HashSet<>();
            for (String id : ids) {
                ResourceLocation location = ResourceLocation.tryParse(id);
                if (location == null || !seen.add(location)) {
                    continue;
                }
                if (hubRegistry.isPresent() && hubRegistry.get().containsKey(location)) {
                    continue;
                }
                entries.add(new RegistrySynchronization.PackedRegistryEntry(location, Optional.empty()));
            }
            if (!entries.isEmpty()) {
                result.put(key, entries);
            }
        });
        return result;
    }

    /**
     * Returns a copy of {@code original} where every tag listed in the manifest that the Hub does not
     * already send is added as an empty tag. Only registries that changed are rewritten; the client
     * replaces tags per registry, so each rewritten registry keeps the Hub's own tags as well.
     */
    public static Map<ResourceKey<? extends Registry<?>>, TagNetworkSerialization.NetworkPayload> mergeTags(
            Map<ResourceKey<? extends Registry<?>>, TagNetworkSerialization.NetworkPayload> original,
            Manifest manifest) {
        Map<ResourceKey<? extends Registry<?>>, TagNetworkSerialization.NetworkPayload> result =
                new HashMap<>(original);
        manifest.tags.forEach((registryId, names) -> {
            ResourceLocation registryLocation = ResourceLocation.tryParse(registryId);
            if (registryLocation == null || names == null || names.isEmpty()) {
                return;
            }
            ResourceKey<? extends Registry<?>> key = ResourceKey.createRegistryKey(registryLocation);
            Map<ResourceLocation, IntList> tags = decode(original.get(key));
            boolean changed = false;
            for (String name : names) {
                ResourceLocation tag = ResourceLocation.tryParse(name);
                if (tag != null && !tags.containsKey(tag)) {
                    tags.put(tag, new IntArrayList());
                    changed = true;
                }
            }
            if (changed) {
                result.put(key, encode(tags));
            }
        });
        return result;
    }

    public static Map<ResourceLocation, IntList> decode(
            @Nullable TagNetworkSerialization.NetworkPayload payload) {
        if (payload == null) {
            return new LinkedHashMap<>();
        }
        FriendlyByteBuf buf = new FriendlyByteBuf(Unpooled.buffer());
        try {
            payload.write(buf);
            return new LinkedHashMap<>(
                    buf.readMap(FriendlyByteBuf::readResourceLocation, FriendlyByteBuf::readIntIdList));
        } finally {
            buf.release();
        }
    }

    public static TagNetworkSerialization.NetworkPayload encode(Map<ResourceLocation, IntList> tags) {
        FriendlyByteBuf buf = new FriendlyByteBuf(Unpooled.buffer());
        try {
            buf.writeMap(tags, FriendlyByteBuf::writeResourceLocation, FriendlyByteBuf::writeIntIdList);
            return TagNetworkSerialization.NetworkPayload.read(buf);
        } finally {
            buf.release();
        }
    }
}
